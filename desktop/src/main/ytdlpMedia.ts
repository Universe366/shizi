export interface YtDlpCookie {
  name: string;
  value: string;
  domain: string;
  path?: string;
  secure?: boolean;
  httpOnly?: boolean;
  expirationDate?: number;
}

/** Netscape cookie 文件内容；yt-dlp 的 --cookies 需要这个格式。 */
export function cookieFileContent(cookies: YtDlpCookie[]): string {
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Shizi; deleted after use.', ''];
  for (const cookie of cookies) {
    if (!cookie?.name || !cookie?.domain) continue;
    const domain = String(cookie.domain);
    const includeSubdomains = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const expires = cookie.expirationDate ? Math.floor(cookie.expirationDate) : 0;
    const prefix = cookie.httpOnly ? '#HttpOnly_' : '';
    lines.push(
      [
        prefix + domain,
        includeSubdomains,
        cookie.path || '/',
        cookie.secure ? 'TRUE' : 'FALSE',
        String(expires),
        cookie.name,
        cookie.value
      ].join('\t')
    );
  }
  return lines.join('\n') + '\n';
}

/** 把当前会话的 Cookie 写成临时 Netscape 文件；用完由调用方删除。 */
export async function writeCookieFile(ses: Session, dir: string): Promise<string> {
  const file = path.join(dir, `cookies-${process.pid}-${Date.now()}.txt`);
  const cookies = await ses.cookies.get({});
  fs.writeFileSync(file, cookieFileContent(cookies as YtDlpCookie[]), {
    encoding: 'utf8',
    mode: 0o600
  });
  return file;
}

export function removeCookieFile(file: string | undefined): void {
  if (!file) return;
  try {
    fs.rmSync(file, { force: true });
  } catch {
    // ignore
  }
}

export function makeTempDir(prefix = 'shizi-ytdlp-'): string {
  return fs.mkdtempSync(path.join(os.tmpdir(), prefix));
}

const BROWSER_UA = `Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/${process.versions.chrome} Safari/537.36 Edg/${process.versions.chrome}`;

/**
 * 直接下载页面已经加载的媒体地址（抖音 MSE 的音频/视频直链等）。
 * 走标签页的 session.fetch，自动带上该站 Cookie。
 */
export async function downloadMediaUrl(
  wc: { session: Session },
  url: string,
  dir: string,
  referer: string,
  options: { signal?: AbortSignal; onProgress?: (percent: number, message: string) => void } = {}
): Promise<string> {
  const response = await wc.session.fetch(url, {
    headers: { 'User-Agent': BROWSER_UA, Referer: referer, Accept: '*/*' },
    signal: options.signal
  });
  if (!response.ok) throw new Error(`媒体下载失败（HTTP ${response.status}）`);
  const total = Number(response.headers.get('content-length')) || 0;
  const chunks: Buffer[] = [];
  let received = 0;
  const reader = response.body?.getReader();
  if (!reader) {
    chunks.push(Buffer.from(await response.arrayBuffer()));
  } else {
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (!value) continue;
      chunks.push(Buffer.from(value));
      received += value.byteLength;
      if (received > 400 * 1024 * 1024) throw new Error('媒体文件过大，已停止下载');
      if (total > 0) {
        options.onProgress?.(
          Math.min(95, Math.round((received / total) * 95)),
          '下载音频…'
        );
      }
    }
  }
  if (!chunks.length) throw new Error('媒体下载为空');
  const file = path.join(dir, 'media.bin');
  fs.writeFileSync(file, Buffer.concat(chunks));
  options.onProgress?.(100, '音频就绪，开始转写…');
  return file;
}

interface RunResult {
  code: number;
  stdout: string;
  stderr: string;
}

const MAX_OUTPUT = 2 * 1024 * 1024;

function runBinary(
  binary: string,
  args: string[],
  options: {
    timeoutMs?: number;
    signal?: AbortSignal;
    onLine?: (line: string) => void;
  } = {}
): Promise<RunResult> {
  return new Promise((resolve, reject) => {
    const child = spawn(binary, args, { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '';
    let stderr = '';
    let settled = false;
    let lineBuffer = '';
    const cap = (value: string, chunk: Buffer) =>
      value.length >= MAX_OUTPUT ? value : (value + chunk.toString()).slice(0, MAX_OUTPUT);
    child.stdout.on('data', (chunk: Buffer) => {
      stdout = cap(stdout, chunk);
      if (!options.onLine) return;
      lineBuffer += chunk.toString();
      const lines = lineBuffer.split(/\r?\n/);
      lineBuffer = lines.pop() || '';
      for (const line of lines) options.onLine(line);
    });
    child.stderr.on('data', (chunk: Buffer) => {
      stderr = cap(stderr, chunk);
    });
    const finish = (error?: Error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      options.signal?.removeEventListener('abort', abort);
      if (error) reject(error);
      else resolve({ code: child.exitCode ?? 0, stdout, stderr });
    };
    const abort = () => {
      try {
        child.kill();
      } catch {
        // ignore
      }
      finish(new Error('已取消'));
    };
    const timer = setTimeout(
      () => {
        try {
          child.kill();
        } catch {
          // ignore
        }
        finish(new Error('yt-dlp 超时'));
      },
      Math.max(5000, options.timeoutMs || 120000)
    );
    timer.unref?.();
    if (options.signal?.aborted) {
      abort();
      return;
    }
    options.signal?.addEventListener('abort', abort, { once: true });
    child.on('error', (error) => finish(error));
    child.on('close', (code) => {
      if (code === 0) finish();
      else {
        finish(
          new Error(`yt-dlp 退出码 ${code}：${stderr.trim().slice(-400) || '没有错误输出'}`)
        );
      }
    });
  });
}

/** 只下载音频（或最小视频流），交给现有 ASR 转写。 */
export async function ytdlpDownloadAudio(
  url: string,
  dir: string,
  cookieFile: string | undefined,
  options: {
    signal?: AbortSignal;
    timeoutMs?: number;
    onProgress?: (percent: number, message: string) => void;
  } = {}
): Promise<string> {
  const binary = await ensureYtDlp(() => undefined);
  const host = (() => {
    try {
      return new URL(url).hostname;
    } catch {
      return '';
    }
  })();
  const args = [
    '--user-agent',
    BROWSER_UA,
    ...(/(^|\.)douyin\.com$/i.test(host)
      ? ['--add-header', 'Referer:https://www.douyin.com/']
      : []),
    '-f',
    'bestaudio/best',
    '--no-playlist',
    '--no-warnings',
    '--newline',
    '--no-part',
    '--socket-timeout',
    '20',
    '--retries',
    '2',
    '-o',
    path.join(dir, 'audio.%(ext)s'),
    ...(cookieFile ? ['--cookies', cookieFile] : []),
    url
  ];
  await runBinary(binary, args, {
    signal: options.signal,
    timeoutMs: options.timeoutMs || 10 * 60 * 1000,
    onLine: (line) => {
      const progress = parseYtDlpProgress(line);
      if (progress) options.onProgress?.(progress.percent, '提取音频…');
    }
  });
  const file = fs
    .readdirSync(dir)
    .filter((name) => name.startsWith('audio.'))
    .map((name) => path.join(dir, name))
    .find((item) => fs.statSync(item).size > 0);
  if (!file) throw new Error('yt-dlp 没有下载到音频');
  return file;
}

export interface YtDlpMediaInfo {
  title?: string;
  duration?: number;
  uploader?: string;
  webpage_url?: string;
}

/** 读元数据（需要更准确的标题时用；失败由调用方兜底）。 */
export async function ytdlpInfo(
  url: string,
  cookieFile: string | undefined,
  signal?: AbortSignal
): Promise<YtDlpMediaInfo> {
  const binary = await ensureYtDlp(() => undefined);
  const args = [
    '-J',
    '--no-warnings',
    '--no-playlist',
    '--no-progress',
    '--socket-timeout',
    '20',
    '--retries',
    '2',
    ...(cookieFile ? ['--cookies', cookieFile] : []),
    url
  ];
  const result = await runBinary(binary, args, { signal, timeoutMs: 60000 });
  const line = result.stdout
    .split(/\r?\n/)
    .map((item) => item.trim())
    .find((item) => item.startsWith('{'));
  if (!line) throw new Error('yt-dlp 没有返回视频信息');
  return JSON.parse(line) as YtDlpMediaInfo;
}
